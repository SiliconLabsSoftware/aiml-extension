/***************************************************************************//**
 * @addtogroup ml_audio_feature_generation_si91x Audio feature generator (Si91x)
 * @ingroup fe_audio
 * The audio feature generator extracts mel-filterbank features
 * from an audio signal to use with machine learning audio classification
 * applications using a microphone as an audio source.
 *
 * @details
 * ## Feature Generation
 *
 * The Mel scale replicates the behavior of the human ear, which has a higher
 * resolution for lower frequencies and is less discriminative of the higher
 * frequencies. To create a mel filterbank, a number of filters are applied
 * to the signal, where the pass-band of the lower channel filters is narrow
 * and increases towards higher frequencies.

 * The audio signal is split into short overlapping segments using
 * a window function (Hamming). The Fast Fourier Transform (FFT) is applied
 * to each segment to retrieve the frequency spectrum and then the power spectrum
 * of the segment. The filterbank is created by applying a series of mel-scaled
 * filters to the output. Finally, the log is applied to the output to increase
 * the sensitivity between the lower channels.
 *
 *              Audio Signal
 *                   │
 *           ┌───────▼───────┐
 *           │   Windowing   │
 *           └───────┬───────┘
 *                   │
 *           ┌───────▼───────┐
 *           │      FFT      │
 *           └───────┬───────┘
 *                   │
 *           ┌───────▼───────┐
 *           │  Mel Filters  │
 *           └───────┬───────┘
 *                   │
 *           ┌───────▼───────┐
 *           │      Log      │
 *           └───────┬───────┘
 *                   │
 *                   ▼
 *        Log-scaled Mel Filterbank
 *
 *
 * The feature array is generated by stacking filterbanks of sequential segments
 * together to form a spectrogram. The array is sorted such that the first element
 * is the first channel of the oldest filterbank.
 *
 * ##  Usage
 * sl_ml_audio_feature_generation_init() initializes the frontend from a per-model
 * @ref sl_fe_audio_config_t (typically @c sl_fe_audio_<instance>_cfg from the fe_audio
 * component). It also starts the microphone in streaming mode into a heap-allocated
 * ring buffer sized from @c config->audio_buffer_size.
 *
 * ### Si91x single pipeline (multi-instance configs)
 * The fe_audio component may define several @c sl_fe_audio_<instance>_cfg symbols (one per
 * model). The Si91x implementation still uses one set of global buffers and one
 * @c FrontendState at a time. Only one pipeline may be active. After validating the new
 * parameters, @ref sl_ml_audio_feature_generation_init and
 * @ref sl_ml_audio_feature_generation_init_with_buffer tear down an existing pipeline
 * (same as @ref sl_ml_audio_feature_generation_deinit) and then bring up the new config, so
 * callers can switch models with a single @c init call.
 *
 * ### Instance configuration (fe_audio)
 * Frontend parameters for inference come from the per-model @c sl_fe_audio_config_t that the
 * fe_audio component exports (typically @c sl_fe_audio_<instance>_cfg in @c sl_fe_audio_instances.h,
 * autogenerated from the same TensorFlow Lite flatbuffer metadata produced by the Silicon Labs
 * converter toolchain). Pass @c &sl_fe_audio_<instance>_cfg to @ref sl_ml_audio_feature_generation_init
 * so the microfrontend, sample rate, ring buffer sizing, and quantization options match that model.
 *
 * The features are generated when sl_ml_audio_feature_generation_update_features()
 * is called. The feature generator then updates the features for as many
 * new segments of audio as possible, starting from the last time the function
 * was called up until the current time. The new features are appended to the
 * feature buffer, replacing the oldest features such that the feature array
 * always contains the most up to date features.
 *
 * Note that if the audio buffer is not large enough to hold all audio samples
 * required to generate features between calls to
 * sl_ml_audio_feature_generation_update_features(), audio data will simply be
 * overwritten. The generator will not return an error. The audio buffer must
 * therefore be configured to be large enough to store all new sampled data
 * between updating features.
 *
 * To retrieve the generated features, either
 * sl_ml_audio_feature_generation_get_features_raw(),
 * sl_ml_audio_feature_generation_get_features_quantized(), or
 * sl_ml_audio_feature_generation_fill_tensor() must be called.
 *
 *
 * ### Example
 *
 * When used with TensorFlow Lite Micro, the audio feature generator can fill the network input
 * tensor via sl_ml_audio_feature_generation_fill_tensor(). Training and inference must use the
 * same frontend pipeline; with instance-based integration that means initializing with the
 * @c sl_fe_audio_config_t generated for the deployed @c .tflite (same embedded FE metadata the
 * converter wrote into the model).
 *
 * ```
 * #include "sl_tflite_micro_init.h"
 * #include "sl_fe_audio_instances.h"
 * #include "sl_fe_audio_si91x.h"
 *
 * void main(void)
 * {
 *   sl_ml_audio_feature_generation_init(&sl_fe_audio_my_model_cfg);
 *
 *   while(1){
 *     sl_ml_audio_feature_generation_update_features();
 *
 *     if(do_inference){
 *       sl_ml_audio_feature_generation_fill_tensor(sl_tflite_micro_get_input_tensor());
 *       sl_tflite_micro_get_interpreter()->Invoke();
 *     }
 *
 *     ...
 *
 *   }
 * }
 *
 * ```
 *
 * Note that updating features and retrieving them can be performed independently.
 * Updating features should be done often enough to avoid overwriting the audio buffer
 * while retrieving them only needs to be done prior to inference.
 * @{
 ******************************************************************************/

/***************************************************************************//**
 * @brief
 *    Set up the microphone as an audio source for feature generation and
 *    initialize the frontend from @p config (allocates the audio ring buffer).
 *
 * @details
 *    If a pipeline is already active, it is torn down first (same as
 *    @ref sl_ml_audio_feature_generation_deinit). A non-OK status from that step is the
 *    return value from @c sl_ml_mic_deinit() during deinit.
 *
 *    After the frontend is initialized, failures from @c sl_ml_mic_init,
 *    @c sl_ml_mic_start_streaming, or @c sl_ml_mic_process_action return that driver
 *    @c sl_status_t after cleaning up allocated resources.
 *
 * @param[in] config
 *    Per-model frontend and buffer parameters; must not be NULL.
 *
 * @retval SL_STATUS_OK Success.
 * @retval SL_STATUS_INVALID_PARAMETER @p config is NULL, @c audio_buffer_size is less than 2, or invalid
 *    parameters from @ref sl_ml_audio_feature_generation_init_with_buffer or the frontend layer.
 * @retval SL_STATUS_FAIL Coarse validation failed (sample rate, window step/size, segment length),
 *    or microfrontend state cannot be populated (@ref sl_ml_audio_feature_generation_frontend_init).
 * @retval SL_STATUS_ALLOCATION_FAILED The heap audio ring or feature ring could not be allocated.
 *
 * @return
 *    Other non-OK @c sl_status_t values may be returned from the microphone / I2S driver
 *    during teardown or bring-up.
 ******************************************************************************/
sl_status_t sl_ml_audio_feature_generation_init(const sl_fe_audio_config_t *config);

/***************************************************************************//**
 * @brief
 *    Initialize audio feature generation with a user-provided buffer.
 *
 * @details
 *    If a pipeline is already active, it is torn down first (same as
 *    @ref sl_ml_audio_feature_generation_deinit). A non-OK status from that step is the
 *    return value from @c sl_ml_mic_deinit() during deinit.
 *
 *    After the frontend is initialized, failures from @c sl_ml_mic_init,
 *    @c sl_ml_mic_start_streaming, or @c sl_ml_mic_process_action return that driver
 *    @c sl_status_t after cleaning up allocated resources.
 *
 * @param[in] buffer
 *    Pointer to the audio buffer to use for feature generation.
 *
 * @param[in] n_frames
 *    Number of int16 audio samples in the buffer; must equal @c config->audio_buffer_size.
 *
 * @param[in] config
 *    Per-model frontend and buffer parameters; must not be NULL.
 *
 * @retval SL_STATUS_OK Success.
 * @retval SL_STATUS_INVALID_PARAMETER @p config or @p buffer is NULL, @p n_frames is less than 2,
 *    @p n_frames does not equal @c config->audio_buffer_size, or invalid frontend parameters
 *    from @ref sl_ml_audio_feature_generation_frontend_init.
 * @retval SL_STATUS_FAIL Coarse validation failed (sample rate, window step/size, segment length),
 *    or microfrontend state cannot be populated.
 * @retval SL_STATUS_ALLOCATION_FAILED The feature ring buffer could not be allocated.
 *
 * @return
 *    Other non-OK @c sl_status_t values may be returned from the microphone / I2S driver
 *    during teardown or bring-up.
 ******************************************************************************/
sl_status_t sl_ml_audio_feature_generation_init_with_buffer(int16_t *buffer,
                                                              int n_frames,
                                                              const sl_fe_audio_config_t *config);

/***************************************************************************//**
 * @brief
 *    Tear down the Si91x audio feature pipeline (mic, internal feature buffer, frontend state).
 *
 * @details
 *    Idempotent: returns @c SL_STATUS_OK if the pipeline was already inactive.
 *    After @ref sl_ml_audio_feature_generation_init, frees the heap audio buffer owned by
 *    that API. Buffers passed to @ref sl_ml_audio_feature_generation_init_with_buffer are
 *    never freed here (caller retains ownership).
 *
 *    Teardown is best-effort: the internal feature buffer and frontend state are always
 *    released after @c sl_ml_mic_deinit() is attempted. If the microphone returns a non-OK
 *    status, the pipeline is still marked inactive and FE memory is freed; the caller may
 *    need to handle or log the mic status separately.
 *
 * @retval SL_STATUS_OK The microphone deinitialized cleanly, or the pipeline was already inactive.
 * @return
 *    If the pipeline was active and @c sl_ml_mic_deinit() returns a value other than
 *    @c SL_STATUS_OK, that status is returned (feature-buffer and frontend teardown may still
 *    have completed).
 ******************************************************************************/
sl_status_t sl_ml_audio_feature_generation_deinit(void);

/***************************************************************************//**
 * @brief
 *    Initialize the microfrontend and feature buffers from @p config.
 *
 * @param[in] config
 *    Per-model frontend and buffer parameters; must not be NULL.
 *
 * @retval SL_STATUS_OK Success.
 * @retval SL_STATUS_INVALID_PARAMETER @p config is NULL, @c audio_buffer_size is zero, zero
 *    filterbank channels, invalid slice-count arithmetic, or window sizing overflow.
 * @retval SL_STATUS_FAIL Inconsistent sample rate / window / segment fields, or
 *    FrontendPopulateState() failed.
 * @retval SL_STATUS_NOT_INITIALIZED @c sl_ml_audio_feature_generation_audio_buffer is NULL
 *    (set the audio ring pointer before calling).
 * @retval SL_STATUS_ALLOCATION_FAILED Feature ring allocation failed.
 ******************************************************************************/
sl_status_t sl_ml_audio_feature_generation_frontend_init(const sl_fe_audio_config_t *config);

/***************************************************************************//**
 * @brief
 *    Advance the audio ring write index after a mic/DMA chunk; optionally apply gain in place.
 *
 * @details
 *    PCM is already in @c sl_ml_audio_feature_generation_audio_buffer (I2S/DMA). @p new_samples
 *    refers to that same backing store (not a separate memcpy source). When gain is greater than 1,
 *    samples are scaled in place.
 *
 * @param[in] new_samples
 *    Pointer to the chunk that was just captured into the audio ring.
 *
 * @param[in] num_samples
 *    Number of int16 samples in this chunk; must stay consistent for the active pipeline.
 *
 * @retval SL_STATUS_OK Success.
 * @retval SL_STATUS_NOT_INITIALIZED The audio ring is not set up.
 ******************************************************************************/
sl_status_t sli_ml_audio_feature_generation_audio_buffer_write_chunk(const int16_t *new_samples, size_t num_samples);

/***************************************************************************//**
 * @brief
 *    Update the feature buffer with feature slices computed since the last call.
 *
 * @details
 *    To retrieve features, call @ref sl_ml_audio_feature_generation_get_features_raw or
 *    @ref sl_ml_audio_feature_generation_fill_tensor.
 *
 * @note
 *    Call often enough that the audio ring is not overwritten.
 *
 * @retval SL_STATUS_OK New feature slices were produced from pending audio.
 * @retval SL_STATUS_EMPTY No new audio to consume, or no new slices from available audio.
 * @retval SL_STATUS_NOT_INITIALIZED Audio ring, feature buffer, or runtime frontend config
 *    is not ready (e.g. after failed re-init or before init completed successfully).
 ******************************************************************************/
sl_status_t sl_ml_audio_feature_generation_update_features();

/***************************************************************************//**
 * @brief
 *    Copy the active spectrogram ring to a @c uint16 buffer.
 *
 * @param[out] buffer
 *    Pointer to the buffer to store the feature data.
 *
 * @param[in] num_elements
 *    Must equal the active feature element count (@ref sl_ml_audio_feature_generation_get_feature_buffer_size).
 *
 * @note
 *    Overwrites the entire @p buffer.
 *
 * @retval SL_STATUS_OK Success.
 * @retval SL_STATUS_NOT_INITIALIZED Feature buffer is not allocated.
 * @retval SL_STATUS_INVALID_PARAMETER @p num_elements does not match the active feature buffer size.
 ******************************************************************************/
sl_status_t sl_ml_audio_feature_generation_get_features_raw(uint16_t *buffer, size_t num_elements);

/***************************************************************************//**
 * @brief
 *    Copy the active spectrogram ring to a @c float32 buffer.
 *
 * @param[out] buffer
 *    Pointer to the buffer to store the feature data.
 *
 * @param[in] num_elements
 *    Must equal the active feature element count (@ref sl_ml_audio_feature_generation_get_feature_buffer_size).
 *
 * @note
 *    Overwrites the entire @p buffer.
 *
 * @retval SL_STATUS_OK Success.
 * @retval SL_STATUS_NOT_INITIALIZED Feature buffer is not allocated.
 * @retval SL_STATUS_INVALID_PARAMETER @p num_elements does not match the active feature buffer size.
 ******************************************************************************/
sl_status_t sl_ml_audio_feature_generation_get_features_raw_float32(float *buffer, size_t num_elements);

/***************************************************************************//**
 * @brief
 *    Quantize the active uint16 spectrogram to int8 in the range -128..127.
 *
 * @details
 *    @p range_min and @p range_max define the uint16 range mapped into int8.
 *
 * @param[out] buffer
 *    Pointer to the buffer to store the feature data.
 *
 * @param[in] num_elements
 *    Must equal the active feature element count (@ref sl_ml_audio_feature_generation_get_feature_buffer_size).
 *
 * @param[in] range_min
 *    Lower bound of the uint16 quantization range.
 *
 * @param[in] range_max
 *    Upper bound of the uint16 quantization range.
 *
 * @note
 *    Overwrites the entire @p buffer.
 *
 * @retval SL_STATUS_OK Success.
 * @retval SL_STATUS_NOT_INITIALIZED Feature buffer is not allocated.
 * @retval SL_STATUS_INVALID_PARAMETER @p num_elements does not match the active feature buffer size,
 *    or @p range_min equals @p range_max.
 ******************************************************************************/
sl_status_t sli_ml_audio_feature_generation_get_features_quantized(int8_t *buffer,
                                                                   size_t num_elements,
                                                                   uint16_t range_min,
                                                                   uint16_t range_max);

/***************************************************************************//**
 * @brief
 *    Quantize the active uint16 spectrogram to int8 using dynamic range scaling.
 *
 * @details
 *    The current frame maximum maps to +127; @c (max - dynamic_range) (clamped at zero) maps to -128,
 *    with linear scaling in between. Values below that floor clamp to -128.
 *
 * @param[out] buffer
 *    Destination for @p num_elements int8 samples.
 *
 * @param[in] num_elements
 *    Must equal the active feature element count (@ref sl_ml_audio_feature_generation_get_feature_buffer_size).
 *
 * @param[in] dynamic_range
 *    Span of uint16 counts mapped into the int8 output. Relates to dynamic range in dB via
 *    @c dynamic_range = DYNAMIC_RANGE_DB*(2^log_scale_shift)*ln(10)/20 (e.g. 300 corresponds to 40 dB).
 *
 * @note
 *    Overwrites the entire @p buffer.
 *
 * @retval SL_STATUS_OK Success.
 * @retval SL_STATUS_NOT_INITIALIZED Feature buffer is not allocated.
 * @retval SL_STATUS_INVALID_PARAMETER @p num_elements does not match the active feature buffer size,
 *    or @p dynamic_range is zero.
 ******************************************************************************/
sl_status_t sli_ml_audio_feature_generation_get_features_dynamically_quantized(int8_t *buffer,
                                                                               size_t num_elements,
                                                                               uint16_t dynamic_range);


/***************************************************************************//**
 * @brief
 *    Copy the active spectrogram to @p buffer with each sample multiplied by @p scaler.
 *
 * @details
 *    Computes @c buffer[i] = (float)feature[i] * @p scaler for each element in the ring.
 *
 * @param[out] buffer
 *    Pointer to the buffer to store the scaled feature data.
 *
 * @param[in] num_elements
 *    Must equal the active feature element count (@ref sl_ml_audio_feature_generation_get_feature_buffer_size).
 *
 * @param[in] scaler
 *    Scaling factor applied to each feature value (must be non-zero).
 *
 * @note
 *    Overwrites the entire @p buffer.
 *
 * @retval SL_STATUS_OK Success.
 * @retval SL_STATUS_NOT_INITIALIZED Feature buffer is not allocated.
 * @retval SL_STATUS_INVALID_PARAMETER @p num_elements does not match the active feature buffer size,
 *    or @p scaler is zero.
 ******************************************************************************/
sl_status_t sl_ml_audio_feature_generation_get_features_scaled(float *buffer, size_t num_elements, float scaler);


/***************************************************************************//**
 * @brief
 *    Mean- and standard-deviation-normalized copy of the active spectrogram into @p buffer.
 *
 * @details
 *    For each element: @c (float(value) - mean) / std. Near-constant input yields zeros in @p buffer.
 *
 * @param[out] buffer
 *    Pointer to the buffer to store the normalized feature data.
 *
 * @param[in] num_elements
 *    Must equal the active feature element count (@ref sl_ml_audio_feature_generation_get_feature_buffer_size).
 *
 * @note
 *    Overwrites the entire @p buffer.
 *
 * @retval SL_STATUS_OK Success.
 * @retval SL_STATUS_NOT_INITIALIZED Feature buffer is not allocated.
 * @retval SL_STATUS_INVALID_PARAMETER @p num_elements does not match the active feature buffer size.
 ******************************************************************************/
sl_status_t sl_ml_audio_feature_generation_get_features_mean_std_normalized(float *buffer, size_t num_elements);


/***************************************************************************//**
 * @brief
 *    Fill a TensorFlow Lite input tensor from the active feature buffer.
 *
 * @details
 *    Writes packed tensor data according to @p input_tensor->type:
 *    - @c kTfLiteInt8: static or dynamically quantized int8 (per active @c sl_fe_audio_config_t).
 *    - @c kTfLiteUInt16: raw uint16 spectrogram.
 *    - @c kTfLiteFloat32: raw float, scaled float, or mean/std-normalized float (per active config).
 *
 * @param[in] input_tensor
 *    The input tensor to fill with features.
 *
 * @note
 *    Overwrites the entire input tensor payload.
 *
 * @retval SL_STATUS_OK Success.
 * @retval SL_STATUS_INVALID_PARAMETER Unsupported tensor type, tensor size mismatch, or a parameter
 *    error from the invoked helper (@ref sl_ml_audio_feature_generation_get_features_raw,
 *    @ref sli_ml_audio_feature_generation_get_features_quantized, etc.).
 * @retval SL_STATUS_NOT_INITIALIZED Feature buffer is not allocated or not initialized.
 ******************************************************************************/
sl_status_t sl_ml_audio_feature_generation_fill_tensor(TfLiteTensor* input_tensor);

/***************************************************************************//**
 * @brief
 *    Return the number of new or unfetched feature slices that have been updated
 *    since the last call to sl_ml_audio_feature_generation_get_features_raw or
 *    sl_ml_audio_feature_generation_fill_tensor.
 *
 * @return
 *    Number of unfetched feature slices (non-negative). Zero if none pending or if the
 *    pipeline is not initialized.
 ******************************************************************************/
int sl_ml_audio_feature_generation_get_new_feature_slice_count();

/***************************************************************************//**
 * @brief
 *    Return the feature buffer size.
 *
 * @return
 *    Number of uint16 feature elements in the active spectrogram ring, or @c 0 if the
 *    pipeline / feature buffer is not initialized.
 ******************************************************************************/
int sl_ml_audio_feature_generation_get_feature_buffer_size();

/***************************************************************************//**
 * @brief
 *    Reset the state of the audio feature generator.
 ******************************************************************************/
void sl_ml_audio_feature_generation_reset();


/***************************************************************************//**
 * @brief
 *    Query whether the activity-detection block has tripped since the last successful read.
 *
 * @details
 *    Call @ref sl_ml_audio_feature_generation_update_features periodically so the detector
 *    advances on new audio.
 *
 * @note
 *    Activity detection must be enabled in the active @c sl_fe_audio_config_t (see
 *    @ref sl_ml_audio_feature_generation_is_activity_detection_enabled).
 *
 * @note
 *    Internal trip state is cleared when this returns @c SL_STATUS_OK; a subsequent call returns
 *    @c SL_STATUS_IN_PROGRESS until new activity is detected.
 *
 * @retval SL_STATUS_OK Activity was detected since the last successful trip.
 * @retval SL_STATUS_IN_PROGRESS Activity detection is enabled but no new trip occurred.
 * @retval SL_STATUS_NOT_AVAILABLE Activity detection is not enabled in the active configuration.
 ******************************************************************************/
sl_status_t sl_ml_audio_feature_generation_activity_detected();

/***************************************************************************//**
 * @brief
 *    Return whether the runtime frontend config has activity detection enabled.
 *
 * @details
 *    After @ref sl_ml_audio_feature_generation_init, reflects the active @c sl_fe_audio_config_t.
 ******************************************************************************/
bool sl_ml_audio_feature_generation_is_activity_detection_enabled(void);

/***************************************************************************//**
 * @brief
 *    Microphone callback function type for audio feature generation.
 *
 * @param[in] arg      User-defined argument passed to the callback.
 * @param[in] data     Pointer to the audio data buffer.
 * @param[in] n_frames Number of audio frames in the buffer.
 ******************************************************************************/
typedef void (*sl_ml_audio_feature_generation_mic_callback_t)(void* arg, const int16_t* data, uint32_t n_frames);

/***************************************************************************//**
 * @brief
 *    Register the optional microphone PCM callback (or clear it).
 *
 * @param[in] callback  Function pointer (may be NULL to clear).
 * @param[in] arg       User argument passed to @p callback.
 *
 * @retval SL_STATUS_OK Always (registration cannot fail in the current implementation).
 ******************************************************************************/
sl_status_t sl_ml_audio_feature_generation_set_mic_callback(sl_ml_audio_feature_generation_mic_callback_t callback, void* arg);

/***************************************************************************//**
 * @brief
 *    External audio buffer for audio feature generation (mic / DMA ring backing store).
 ******************************************************************************/
extern int16_t* sl_ml_audio_feature_generation_audio_buffer;


