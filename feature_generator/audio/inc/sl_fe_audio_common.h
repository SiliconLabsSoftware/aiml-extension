/**
 * @struct sl_fe_audio_config
 * @details
 * Runtime frontend, buffer, and quantization parameters for one fe_audio component
 * instance. Applications normally pass @c &sl_fe_audio_<instance>_cfg from
 * @c sl_fe_audio_instances.h to @ref sl_ml_audio_feature_generation_init.
 *
 * Each @c sl_fe_audio_<instance>_cfg symbol is defined in autogenerated
 * @c sl_fe_audio_instances.c from @c sl_fe_audio_<instance>_config.h. Per-parameter
 * documentation and Simplicity Studio Configuration Wizard entries live in that
 * instance config header (model metadata from the trained @c .tflite); do not
 * document or edit individual fields here.
 */
typedef struct sl_fe_audio_config {
  struct FrontendConfig frontend_config;
  int sample_rate_hz;
  unsigned fft_length;
  unsigned sample_length_ms;
  size_t audio_buffer_size;
  size_t audio_buffer_chunk_size;
  int audio_gain;
  int quantize_dynamic_scale_enable;
  float quantize_dynamic_scale_range_db;
  uint16_t quantize_feature_range_min;
  uint16_t quantize_feature_range_max;
  float samplewise_norm_rescale;
  int samplewise_norm_mean_and_std;
} sl_fe_audio_config_t;

/***************************************************************************//**
 * @brief
 *    Compute the number of uint16 elements in the feature ring buffer for @p config.
 *
 * @details
 *    Calls @ref sli_fe_audio_validate_config, then computes
 *    `slice_count = 1 + (sample_length_ms - window_size_ms) / window_step_ms`
 *    multiplied by filterbank channel count. Returns @c SL_STATUS_INVALID_PARAMETER when
 *    channel count is zero or the product would overflow @c size_t.
 *
 * @param[in] config
 *    Frontend configuration (must be non-NULL).
 * @param[out] element_count
 *    Receives `slice_count * num_channels` on success (must be non-NULL).
 *
 * @retval SL_STATUS_OK Feature buffer size computed successfully.
 * @return
 *    Status from @ref sli_fe_audio_validate_config, or @c SL_STATUS_INVALID_PARAMETER when
 *    @p element_count is NULL, channel count is zero, or the product would overflow @c size_t.
 ******************************************************************************/
sl_status_t sli_fe_audio_compute_feature_buffer_element_count(const sl_fe_audio_config_t *config,
                                                              size_t *element_count);

/***************************************************************************//**
 * @brief
 *    Validate common frontend timing and sample-rate fields in @p config.
 *
 * @details
 *    Checks non-NULL @p config, positive @c sample_rate_hz, non-zero window step,
 *    @c sample_length_ms greater than window size, and non-zero @c audio_buffer_size.
 *    Platform code may apply additional chunk or buffer-length checks after this call.
 *
 * @param[in] config
 *    Frontend configuration (must be non-NULL).
 *
 * @retval SL_STATUS_OK Configuration is valid.
 * @retval SL_STATUS_INVALID_PARAMETER @p config is NULL or @c audio_buffer_size is zero.
 * @retval SL_STATUS_FAIL Sample rate or window timing is invalid.
 ******************************************************************************/
sl_status_t sli_fe_audio_validate_config(const sl_fe_audio_config_t *config);

/***************************************************************************//**
 * @addtogroup ml_audio_feature_generation_common Audio feature math (shared core)
 * @ingroup fe_audio
 *
 * Shared @ref sl_fe_audio_config_t and toolchain-neutral, side-effect-free feature-extraction
 * math used by both platform implementations. Quantizer and normalization helpers must stay
 * bit-identical across targets, so they live in a single plain-C translation unit.
 *
 * Each feature accessor reads `count` elements from a circular feature buffer in logical
 * order: element `i` is `feature_buffer[(start + i) % count]`. The caller owns validation
 * (NULL checks, element-count checks, parameter ranges) and ring-index bookkeeping; these
 * helpers only compute outputs.
 * @{
 ******************************************************************************/

/***************************************************************************//**
 * @brief
 *    Compute the integer dynamic-scale range used by the dynamic int8 quantizer.
 *
 * @details
 *    Mirrors the per-model derivation `range_db * 2^log_scale_shift * ln(10)/20`.
 *    Returns `0` when dynamic scaling is disabled.
 *
 * @param[in] dynamic_scale_enable
 *    Non-zero to enable dynamic scaling (from `quantize_dynamic_scale_enable`).
 * @param[in] dynamic_scale_range_db
 *    Dynamic range in dB (from `quantize_dynamic_scale_range_db`).
 * @param[in] log_scale_shift
 *    Log-scale shift from the frontend config (`log_scale.scale_shift`).
 *
 * @return
 *    The integer dynamic-scale range, or `0` when disabled.
 ******************************************************************************/
int sli_fe_audio_compute_dynamic_scale_range(int dynamic_scale_enable,
                                             float dynamic_scale_range_db,
                                             unsigned log_scale_shift);

/***************************************************************************//**
 * @brief
 *    Copy `count` uint16 features (logical order from `start`) into `out`.
 ******************************************************************************/
void sli_fe_audio_features_to_u16(const uint16_t *feature_buffer,
                                  size_t count,
                                  size_t start,
                                  uint16_t *out);

/***************************************************************************//**
 * @brief
 *    Copy `count` features into `out` as float32 (logical order from `start`).
 ******************************************************************************/
void sli_fe_audio_features_to_f32(const uint16_t *feature_buffer,
                                  size_t count,
                                  size_t start,
                                  float *out);

/***************************************************************************//**
 * @brief
 *    Static int8 quantization of `count` features into `out`.
 *
 * @details
 *    `out[i] = clamp(((feature - range_min) * 256 + (div / 2)) / div - 128, -128, 127)`
 *    where `div = range_max - range_min`. The caller must ensure
 *    `range_min != range_max`.
 ******************************************************************************/
void sli_fe_audio_quantize_i8(const uint16_t *feature_buffer,
                              size_t count,
                              size_t start,
                              uint16_t range_min,
                              uint16_t range_max,
                              int8_t *out);

/***************************************************************************//**
 * @brief
 *    Dynamic int8 quantization of `count` features into `out`.
 *
 * @details
 *    Maps the per-call maximum to `+127` and `max - dynamic_range` (clamped at zero)
 *    to `-128`. The caller must ensure `dynamic_range != 0`.
 ******************************************************************************/
void sli_fe_audio_dynamic_quantize_i8(const uint16_t *feature_buffer,
                                      size_t count,
                                      size_t start,
                                      uint16_t dynamic_range,
                                      int8_t *out);

/***************************************************************************//**
 * @brief
 *    Scaled float copy: `out[i] = (float)feature * scaler`.
 *
 * @details
 *    The caller must ensure `scaler != 0`.
 ******************************************************************************/
void sli_fe_audio_scale_f32(const uint16_t *feature_buffer,
                            size_t count,
                            size_t start,
                            float scaler,
                            float *out);

/***************************************************************************//**
 * @brief
 *    Mean/standard-deviation normalized float copy: `out[i] = (feature - mean) / std`.
 *
 * @details
 *    Uses population standard deviation. A near-constant spectrogram
 *    (`std < 1e-6`) yields all zeros to avoid dividing by (near) zero.
 ******************************************************************************/
void sli_fe_audio_mean_std_normalize_f32(const uint16_t *feature_buffer,
                                         size_t count,
                                         size_t start,
                                         float *out);

